#!/usr/bin/env node
// One-off generator: parses the official SCIAN (INEGI) catalog xlsx into the
// static TS data files under lib/scian/. Re-run this if INEGI publishes a
// new SCIAN version:
//
//   node scripts/generate-scian-catalog.mjs /path/to/scian_catalog.xlsx
//
// The xlsx itself is not committed to the repo — only the generated output.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const XLSX_PATH = process.argv[2];
if (!XLSX_PATH) {
  console.error("Usage: node scripts/generate-scian-catalog.mjs <path-to-scian-xlsx>");
  process.exit(1);
}

function readEntry(name) {
  return execFileSync("unzip", ["-p", XLSX_PATH, name], { maxBuffer: 1024 * 1024 * 50 }).toString("utf8");
}

function decodeXmlEntities(s) {
  return s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");
}

function parseSharedStrings(xml) {
  const strings = [];
  const siRe = /<si>([\s\S]*?)<\/si>/g;
  let m;
  while ((m = siRe.exec(xml))) {
    const block = m[1];
    const tRe = /<t[^>]*>([\s\S]*?)<\/t>/g;
    let text = "";
    let tm;
    while ((tm = tRe.exec(block))) text += tm[1];
    strings.push(decodeXmlEntities(text));
  }
  return strings;
}

// Returns one { a, b } pair per <row> (columns A and B only — code + título).
function parseSheetRows(xml, shared) {
  const rows = [];
  const rowRe = /<row[^>]*>([\s\S]*?)<\/row>/g;
  let rm;
  while ((rm = rowRe.exec(xml))) {
    const rowXml = rm[1];
    const cellRe = /<c r="([A-Z]+)\d+"(?:\s+[^>]*?t="([^"]*)")?[^>]*>(?:<v>([\s\S]*?)<\/v>)?<\/c>/g;
    let cm;
    let a = null;
    let b = null;
    while ((cm = cellRe.exec(rowXml))) {
      const [, col, type, v] = cm;
      if (v == null) continue;
      const text = type === "s" ? shared[Number(v)] : decodeXmlEntities(v);
      if (col === "A") a = text;
      if (col === "B") b = text;
    }
    rows.push({ a, b });
  }
  return rows;
}

const shared = parseSharedStrings(readEntry("xl/sharedStrings.xml"));

// sheet2.xml = SECTOR (rId2), sheet3.xml = SUBSECTOR (rId3), sheet6.xml =
// CLASE (rId6) — confirmed via xl/_rels/workbook.xml.rels against the sheet
// names in xl/workbook.xml.
const sectorRows = parseSheetRows(readEntry("xl/worksheets/sheet2.xml"), shared)
  .slice(2)
  .filter((r) => r.a)
  .map((r) => ({ code: r.a.trim(), title: (r.b || "").trim().replace(/T\s*$/, "").trim() }));

const subsectorRows = parseSheetRows(readEntry("xl/worksheets/sheet3.xml"), shared)
  .slice(2)
  .filter((r) => r.a)
  .map((r) => ({ code: String(r.a).trim(), title: (r.b || "").trim().replace(/T\s*$/, "").trim() }));

const classRows = parseSheetRows(readEntry("xl/worksheets/sheet6.xml"), shared)
  .slice(2)
  .filter((r) => r.a)
  .map((r) => ({ code: r.a.trim(), title: (r.b || "").trim() }));

function sectorForCode(code) {
  const prefix = Number(code.slice(0, 2));
  for (const s of sectorRows) {
    const parts = s.code.split("-").map(Number);
    const lo = parts[0];
    const hi = parts.length > 1 ? parts[1] : parts[0];
    if (prefix >= lo && prefix <= hi) return s.title;
  }
  return "Otros";
}

const subsectorByCode = new Map(subsectorRows.map((s) => [s.code, s.title]));
function subsectorForCode(code) {
  // Subsector codes are 3 digits; some are stored as e.g. "111" (already 3
  // digits) or shorter with a leading-zero convention — the class code's
  // first 3 digits are the canonical lookup key.
  const prefix3 = code.slice(0, 3);
  return subsectorByCode.get(prefix3) ?? "Otros";
}

const catalog = classRows.map((c) => ({
  code: c.code,
  title: c.title,
  sector: sectorForCode(c.code),
  subsector: subsectorForCode(c.code),
}));

const catalogTs = `// Generated by scripts/generate-scian-catalog.mjs — do not edit by hand.
// Source: INEGI SCIAN catalog (Sistema de Clasificación Industrial de
// América del Norte, México), CLASE-level (6-digit) categories — this is
// the granularity DENUE stores in its "Clase_actividad" field, so these
// títulos double as reliable DENUE search keywords.
export interface ScianClass {
  code: string;
  title: string;
  sector: string;
  subsector: string;
}

export const SCIAN_CATALOG: ScianClass[] = ${JSON.stringify(catalog, null, 2)};
`;

const sectorsTs = `// Generated by scripts/generate-scian-catalog.mjs — do not edit by hand.
export interface ScianSector {
  code: string;
  title: string;
}

export const SCIAN_SECTORS: ScianSector[] = ${JSON.stringify(sectorRows, null, 2)};
`;

const outDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "scian");
writeFileSync(path.join(outDir, "catalog.ts"), catalogTs);
writeFileSync(path.join(outDir, "sectors.ts"), sectorsTs);

console.log(`Wrote ${catalog.length} classes and ${sectorRows.length} sectors to lib/scian/`);
