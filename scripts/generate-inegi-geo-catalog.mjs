#!/usr/bin/env node
// One-off generator: parses INEGI's entidad (state) and municipio catalogs
// into static TS data under lib/inegi/. Used only by the standalone
// "advanced search" tool (SCIAN code + Estado + Municipio picker) — not
// related to the regular pill/keyword project search.
//
//   node scripts/generate-inegi-geo-catalog.mjs <entidad.csv> <municipio.csv>
//
// Note: the entidad CSV supplied was Latin-1 encoded, the municipio CSV was
// UTF-8 — each is decoded accordingly; adjust here if a future source differs.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const [entidadPath, municipioPath] = process.argv.slice(2);
if (!entidadPath || !municipioPath) {
  console.error("Usage: node scripts/generate-inegi-geo-catalog.mjs <entidad.csv> <municipio.csv>");
  process.exit(1);
}

// Minimal CSV parser for these simple, fully-quoted, no-embedded-comma files.
function parseCsv(text) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim().length > 0);
  return lines.slice(1).map((line) =>
    line.split(",").map((cell) => cell.trim().replace(/^"|"$/g, ""))
  );
}

const entidadRows = parseCsv(readFileSync(entidadPath, "latin1"));
const municipioRows = parseCsv(readFileSync(municipioPath, "utf8"));

// entidad CSV columns: CVEGEO,CVE_ENT,NOM_ENT,NOM_ABR,...
const entidades = entidadRows.map((r) => ({ code: r[1], name: r[2] }));

// municipio CSV columns: CVEGEO,CVE_ENT,NOM_ENT,NOM_ABR,CVE_MUN,NOM_MUN,...
const municipios = municipioRows.map((r) => ({
  entidadCode: r[1],
  municipioCode: r[4],
  name: r[5],
}));

const entidadesTs = `// Generated by scripts/generate-inegi-geo-catalog.mjs — do not edit by hand.
// INEGI's 32 entidades federativas (states), for the standalone advanced
// search tool's Estado picker.
export interface Entidad {
  code: string;
  name: string;
}

export const ENTIDADES: Entidad[] = ${JSON.stringify(entidades, null, 2)};
`;

const municipiosTs = `// Generated by scripts/generate-inegi-geo-catalog.mjs — do not edit by hand.
// INEGI's ~2,478 municipios, for the standalone advanced search tool's
// Municipio picker (filtered by the chosen entidad).
export interface Municipio {
  entidadCode: string;
  municipioCode: string;
  name: string;
}

export const MUNICIPIOS: Municipio[] = ${JSON.stringify(municipios, null, 2)};
`;

const outDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "inegi");
writeFileSync(path.join(outDir, "entidades.ts"), entidadesTs);
writeFileSync(path.join(outDir, "municipios.ts"), municipiosTs);

console.log(`Wrote ${entidades.length} entidades and ${municipios.length} municipios to lib/inegi/`);
